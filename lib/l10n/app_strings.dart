import 'package:flutter/widgets.dart';

import 'app_localizations.dart';

/// Runtime text lookup used by the UI for messages that contain business
/// terminology or dynamic values. The stable keys are kept in Chinese for
/// backwards compatibility with the existing UI copy and exported data.
///
/// Domain data such as customer names and user-entered notes is intentionally
/// not passed through this lookup.
String localizedText(
  String locale,
  String key, [
  Map<String, Object?> values = const {},
]) {
  var value = locale.startsWith('en')
      ? _english[key] ?? _englishDynamic(key) ?? key
      : key;
  for (final entry in values.entries) {
    value = value.replaceAll('{${entry.key}}', '${entry.value}');
  }
  return value;
}

String? _englishDynamic(String key) {
  final purchase = RegExp(r'^购买验证失败（(.+)）$').firstMatch(key);
  if (purchase != null) {
    return 'Purchase verification failed (${purchase.group(1)}).';
  }
  final service = RegExp(r'^授权服务错误：(.+)$').firstMatch(key);
  if (service != null) {
    return 'License service error (${service.group(1)}).';
  }
  return null;
}

extension AppStringsBuildContext on BuildContext {
  String tr(String key) => localizedText(
        AppLocalizations.of(this).localeName,
        key,
      );

  String trf(String key, Map<String, Object?> values) => localizedText(
        AppLocalizations.of(this).localeName,
        key,
        values,
      );
}

